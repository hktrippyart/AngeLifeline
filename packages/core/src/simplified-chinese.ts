/** 廣東話「係」— 避免簡體「系」作判斷詞 */
const COPULA_FIX: [RegExp, string][] = [
  [/唔系/g, "唔係"],
  [/系令/g, "係令"],
  [/系帮/g, "係幫"],
  [/系将/g, "係將"],
  [/系 /g, "係 "],
  [/ 系/g, " 係"],
  [/做嘅系/g, "做嘅係"],
  [/唔系/g, "唔係"],
  [/归无厘头，道理系咁/g, "歸無厘頭，道理係咁"],
  [/道理系咁/g, "道理係咁"],
  [/做嘅系/g, "做嘅係"],
];

export function toTraditionalHant(text: string): string {
  let out = [...text].map((ch) => S2T.get(ch) ?? ch).join("");
  for (const [pattern, replacement] of COPULA_FIX) {
    out = out.replace(pattern, replacement);
  }
  return out;
}

/** True if text includes mainland simplified characters (not used on this site). */
export function textContainsSimplifiedChinese(text: string): boolean {
  for (const ch of text) {
    if (S2T.has(ch)) return true;
  }
  return false;
}
